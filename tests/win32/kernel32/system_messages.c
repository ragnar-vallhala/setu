int main(void)
{
    static wchar_t buf[4096];
    char name[32];
    unsigned i;
    oracle_begin("kernel32/system_messages");
    for (i = 0; i < sizeof(ids) / sizeof(ids[0]); i++)
    {
        DWORD r;
        ORACLE_CALL(r, FormatMessageW(FORMAT_MESSAGE_FROM_SYSTEM | FORMAT_MESSAGE_IGNORE_INSERTS, NULL, ids[i],
                                      MAKELANGID(LANG_NEUTRAL, SUBLANG_DEFAULT), buf, 4096, NULL));
        sprintf(name, "m_%08lx", (unsigned long)ids[i]);
        oracle_case(name);
        o_u32("ret", r);
        if (!r) o_lasterr();
        if (r && r < 4096) o_wstr("out", buf);
        oracle_case_end();
    }
    return oracle_end();
}
